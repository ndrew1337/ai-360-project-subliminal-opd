"""Results table: the ONE place numbers live.

Scans runs/{slug}/seed-{n}/ for run_manifest.json + eval-{preference}/*/stats.json
(written by upstream run_evaluation_preferences.py), aggregates the final
checkpoint's p_target across seeds per cell, and emits RESULTS.md plus a
machine-readable results.json. Cite results as slug + seeds + commit.
"""

from __future__ import annotations

import json
import re
from pathlib import Path


def _final_checkpoint(eval_dir: Path) -> Path | None:
    """The highest-numbered checkpoint-* with a stats.json ('base' and 'final'
    are ignored: base is the unfinetuned reference, final duplicates the last
    checkpoint)."""
    best, best_step = None, -1
    for child in eval_dir.iterdir():
        match = re.fullmatch(r"checkpoint-(\d+)", child.name)
        if match and (child / "stats.json").exists():
            step = int(match.group(1))
            if step > best_step:
                best, best_step = child, step
    return best


def collect_runs(runs_root: str | Path = "runs") -> list[dict]:
    """One record per (slug, seed, preference): the final-checkpoint stats."""
    records = []
    for manifest_path in sorted(Path(runs_root).glob("*/seed-*/run_manifest.json")):
        run_dir = manifest_path.parent
        if run_dir.parent.name.startswith("_"):
            continue  # smoke/scratch runs are parked under _-prefixed dirs
        manifest = json.loads(manifest_path.read_text())
        seed_match = re.match(r"seed-(\d+)", run_dir.name)
        if seed_match is None:
            continue
        for eval_dir in sorted(run_dir.glob("eval-*")):
            ckpt = _final_checkpoint(eval_dir)
            if ckpt is None:
                continue
            stats = json.loads((ckpt / "stats.json").read_text())
            records.append({
                "slug": manifest["slug"],
                "seed": int(seed_match.group(1)),
                "condition": manifest.get("condition", "?"),
                "preference": eval_dir.name.removeprefix("eval-"),
                "checkpoint": ckpt.name,
                "p_target": stats["mean"],
                "margin_error": stats.get("margin_error"),
                "commit": manifest.get("code_commit", "?"),
            })
    return records


def aggregate(records: list[dict]) -> list[dict]:
    """Across-seed aggregation per (slug, condition, preference)."""
    groups: dict[tuple, list[dict]] = {}
    for r in records:
        groups.setdefault((r["slug"], r["condition"], r["preference"]), []).append(r)
    rows = []
    for (slug, condition, preference), group in sorted(groups.items()):
        values = [g["p_target"] for g in sorted(group, key=lambda g: g["seed"])]
        n = len(values)
        mean = sum(values) / n
        std = (sum((v - mean) ** 2 for v in values) / (n - 1)) ** 0.5 if n > 1 else 0.0
        rows.append({
            "slug": slug,
            "condition": condition,
            "preference": preference,
            "mean": round(mean, 4),
            "std": round(std, 4),
            "n_seeds": n,
            "seeds": [g["seed"] for g in sorted(group, key=lambda g: g["seed"])],
            "per_seed": [round(v, 4) for v in values],
            "commits": sorted({g["commit"] for g in group}),
        })
    return rows


def render_markdown(rows: list[dict]) -> str:
    lines = [
        "# Results",
        "",
        "Generated by `python scripts/make_results.py` — do not edit numbers by hand.",
        "",
        "| slug | condition | preference | p_target (mean ± std) | seeds | per-seed | commit |",
        "|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        per_seed = ", ".join(f"{v:.3f}" for v in r["per_seed"])
        lines.append(
            f"| {r['slug']} | {r['condition']} | {r['preference']} "
            f"| {r['mean']:.4f} ± {r['std']:.4f} | {r['n_seeds']} ({', '.join(map(str, r['seeds']))}) "
            f"| {per_seed} | {', '.join(r['commits'])} |"
        )
    return "\n".join(lines) + "\n"


def write_results(runs_root: str | Path = "runs", out_md: str | Path = "RESULTS.md",
                  out_json: str | Path = "results.json") -> list[dict]:
    rows = aggregate(collect_runs(runs_root))
    Path(out_md).write_text(render_markdown(rows))
    Path(out_json).write_text(json.dumps(rows, indent=2) + "\n")
    return rows
